import sys
import uuid
from typing import Any, Optional

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
if hasattr(sys.stderr, "reconfigure"):
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")

from fastapi import FastAPI, HTTPException, Query
from fastapi.middleware.cors import CORSMiddleware
from langchain_core.messages import HumanMessage
from langgraph.types import Command
from pydantic import BaseModel, Field

from graph import app as graph_app

app = FastAPI(
    title="Travel Planning Multi-Agent API",
    description="FastAPI service powered by LangGraph for multi-agent travel planning.",
    version="1.0.0",
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


class AskRequest(BaseModel):
    query: Optional[str] = Field(
        None,
        description="The travel request or question (e.g., 'Plan a 7-day Japan trip under Rs. 2 lakh')",
    )
    question: Optional[str] = Field(
        None,
        description="Alias for query",
    )
    prompt: Optional[str] = Field(
        None,
        description="Alias for query",
    )
    message: Optional[str] = Field(
        None,
        description="Alias for query",
    )
    user_id: Optional[str] = Field(
        "demo_user",
        description="User identifier",
    )
    thread_id: Optional[str] = Field(
        None,
        description="Session thread ID. If omitted, a new thread ID is automatically generated.",
    )
    auto_approve: Optional[bool] = Field(
        True,
        description="If True, automatically approves the draft itinerary and returns the finalized plan.",
    )
    approved: Optional[bool] = Field(
        None,
        description="Human approval decision (True for approve, False for revise). Required when resuming an interrupted thread.",
    )
    feedback: Optional[str] = Field(
        "",
        description="Optional feedback for revision when reviewing or approving.",
    )

    def get_query(self) -> str:
        for val in [self.query, self.question, self.prompt, self.message]:
            if val and val.strip():
                return val.strip()
        return ""


class AskResponse(BaseModel):
    status: str = Field(..., description="Status of the request: 'success', 'waiting_for_approval', or 'error'")
    thread_id: str = Field(..., description="Thread ID used for session state")
    response: str = Field(..., description="Main response text (final travel plan, draft itinerary, or message)")
    final_response: Optional[str] = Field(None, description="Final travel plan generated by the agents")
    itinerary: Optional[str] = Field(None, description="Draft or current itinerary")
    supervisor_reasoning: Optional[str] = Field(None, description="Supervisor agent routing reasoning")
    selected_agents: list[str] = Field(default_factory=list, description="Specialist agents invoked")
    flight_results: Optional[str] = Field(None, description="Flight specialist output")
    hotel_results: Optional[str] = Field(None, description="Hotel specialist output")
    weather_results: Optional[str] = Field(None, description="Weather specialist output")
    budget_results: Optional[str] = Field(None, description="Budget specialist output")
    llm_calls: int = Field(0, description="Total LLM calls made during the session")
    waiting_for_approval: bool = Field(False, description="Whether the graph is waiting for human approval")
    approval_request: Optional[str] = Field(None, description="Approval prompt if waiting for approval")


def _execute_graph(
    query_text: str,
    user_id: str,
    thread_id: str,
    approved: Optional[bool],
    feedback: str,
    auto_approve: bool,
) -> AskResponse:
    config = {"configurable": {"thread_id": thread_id}}

    try:
        # Case 1: Resuming an existing thread with approval / feedback
        if approved is not None and not query_text:
            result = graph_app.invoke(
                Command(
                    resume={
                        "approved": approved,
                        "feedback": feedback or "",
                    }
                ),
                config=config,
            )
        # Case 2: New or ongoing query
        elif query_text:
            initial_state = {
                "messages": [HumanMessage(content=query_text)],
                "user_id": user_id,
                "user_query": query_text,
                "flight_results": "",
                "hotel_results": "",
                "weather_results": "",
                "budget_results": "",
                "itinerary": "",
                "final_response": "",
                "llm_calls": 0,
            }
            result = graph_app.invoke(initial_state, config=config)

            # Check if execution paused at human-in-the-loop interrupt
            if "__interrupt__" in result:
                if auto_approve or approved is not None:
                    approval_decision = True if approved is None else approved
                    result = graph_app.invoke(
                        Command(
                            resume={
                                "approved": approval_decision,
                                "feedback": feedback or "",
                            }
                        ),
                        config=config,
                    )
        else:
            raise HTTPException(
                status_code=400,
                detail="Either 'query' must be provided or ('approved' with 'thread_id') to resume approval.",
            )

        # Determine if still waiting for approval
        is_interrupted = "__interrupt__" in result
        approval_req = ""
        draft_itinerary = ""

        if is_interrupted:
            interrupts = result.get("__interrupt__", [])
            if interrupts and hasattr(interrupts[0], "value") and isinstance(interrupts[0].value, dict):
                int_val = interrupts[0].value
                draft_itinerary = int_val.get("draft_itinerary", "")
                approval_req = int_val.get("approval_request", "")
            draft_itinerary = draft_itinerary or result.get("itinerary", "")
            response_text = draft_itinerary or "Draft itinerary ready. Waiting for human approval."
            status = "waiting_for_approval"
        else:
            final_resp = result.get("final_response", "")
            itinerary = result.get("itinerary", "")
            response_text = final_resp or itinerary or result.get("supervisor_reasoning", "")
            status = "success"

        return AskResponse(
            status=status,
            thread_id=thread_id,
            response=response_text,
            final_response=result.get("final_response") or None,
            itinerary=draft_itinerary or result.get("itinerary") or None,
            supervisor_reasoning=result.get("supervisor_reasoning") or None,
            selected_agents=result.get("selected_agents") or [],
            flight_results=result.get("flight_results") or None,
            hotel_results=result.get("hotel_results") or None,
            weather_results=result.get("weather_results") or None,
            budget_results=result.get("budget_results") or None,
            llm_calls=result.get("llm_calls", 0),
            waiting_for_approval=is_interrupted,
            approval_request=approval_req or result.get("approval_request") or None,
        )

    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(
            status_code=500,
            detail=f"Error executing agent workflow: {str(exc)}",
        ) from exc

@app.post("/ask", response_model=AskResponse)
def ask_post(req: AskRequest):
    query_text = req.get_query()
    thread_id = req.thread_id or f"{req.user_id or 'user'}_{uuid.uuid4().hex[:8]}"
    return _execute_graph(
        query_text=query_text,
        user_id=req.user_id or "demo_user",
        thread_id=thread_id,
        approved=req.approved,
        feedback=req.feedback or "",
        auto_approve=req.auto_approve if req.auto_approve is not None else True,
    )


@app.get("/ask", response_model=AskResponse)
def ask_get(
    query: Optional[str] = Query(None, description="Travel query"),
    thread_id: Optional[str] = Query(None, description="Thread ID"),
    user_id: Optional[str] = Query("demo_user", description="User ID"),
    auto_approve: bool = Query(True, description="Auto approve draft"),
    approved: Optional[bool] = Query(None, description="Approve decision"),
    feedback: Optional[str] = Query("", description="Feedback"),
):
    thread_id = thread_id or f"{user_id}_{uuid.uuid4().hex[:8]}"
    return _execute_graph(
        query_text=(query or "").strip(),
        user_id=user_id,
        thread_id=thread_id,
        approved=approved,
        feedback=feedback or "",
        auto_approve=auto_approve,
    )

